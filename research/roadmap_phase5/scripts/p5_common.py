def sha256(p: Path) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def holm(p):
    p = np.asarray(p, float)
    o = np.argsort(p)
    adj, run = np.empty(len(p)), 0.0
    for i, j in enumerate(o):
        run = max(run, (len(p) - i) * p[j])
        adj[j] = min(1.0, run)
    return adj


def singscore_up(R, idx, N=None):
    """R: samples x genes ranks (ascending). Foroutan 2018 normalised mean-rank score, centred at 0."""
    N = R.shape[1] if N is None else N
    n = len(idx)
    smin, smax = (n + 1) / 2, (2 * N - n + 1) / 2
    return (R[:, idx].mean(1) - smin) / (smax - smin) - 0.5


def singscore_signed(R, up, dn):
    N = R.shape[1]
    return singscore_up(R, up) + singscore_up(N + 1 - R, dn)


def ranks(M: pd.DataFrame) -> np.ndarray:
    """M: genes x samples -> samples x genes within-sample average ranks."""
    return np.apply_along_axis(stats.rankdata, 1, M.T.values.astype(float))


