def welch_ci(a, b, level=.95):
    a, b = np.asarray(a, float), np.asarray(b, float)
    d = a.mean() - b.mean()
    va, vb = a.var(ddof=1) / len(a), b.var(ddof=1) / len(b)
    se = np.sqrt(va + vb)
    df = (va + vb) ** 2 / (va**2 / (len(a) - 1) + vb**2 / (len(b) - 1)) if se > 0 else np.nan
    q = stats.t.ppf(.5 + level / 2, df) if se > 0 else np.nan
    sp = np.sqrt(((len(a) - 1) * a.var(ddof=1) + (len(b) - 1) * b.var(ddof=1)) / (len(a) + len(b) - 2))
    J = 1 - 3 / (4 * (len(a) + len(b)) - 9)
    return dict(estimate=d, se=se, df=df, ci_low=d - q * se, ci_high=d + q * se,
                p_welch=2 * stats.t.sf(abs(d / se), df) if se > 0 else np.nan, hedges_g=J * d / sp if sp > 0 else np.nan)


