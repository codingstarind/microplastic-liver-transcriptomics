"""Verify DOIs against the Crossref REST API and write references.bib + reference_verification.csv.
Read-only with respect to research outputs. Generic User-Agent (no personal data sent).
Input: candidate_references.csv (key, doi, used_in, purpose, access_note)."""
import csv
import json
import re
import time
import urllib.parse
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
AUD = HERE.parent
UA = {"User-Agent": "BT3041-course-reference-check/0.1"}
rows = list(csv.DictReader(open(HERE / "candidate_references.csv", encoding="utf-8")))
cache_f = HERE / "crossref_cache.json"
cache = json.loads(cache_f.read_text()) if cache_f.exists() else {}


def fetch(doi):
    if doi in cache:
        return cache[doi]
    url = "https://api.crossref.org/works/" + urllib.parse.quote(doi)
    for a in range(3):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
                m = json.loads(r.read())["message"]
                cache[doi] = m
                cache_f.write_text(json.dumps(cache))
                return m
        except urllib.error.HTTPError as e:
            if e.code == 404:
                cache[doi] = None
                return None
            time.sleep(3)
        except Exception:  # noqa: BLE001
            time.sleep(3)
    return "ERROR"


def bibtex(key, m, doi):
    au = " and ".join(f"{a.get('family', '')}, {a.get('given', '')}".strip(", ") for a in m.get("author", [])[:12])
    if len(m.get("author", [])) > 12:
        au += " and others"
    year = (m.get("issued", {}).get("date-parts") or [[None]])[0][0]
    typ = {"journal-article": "article", "proceedings-article": "inproceedings", "book": "book", "book-chapter": "incollection",
           "posted-content": "misc"}.get(m.get("type"), "misc")
    f = dict(author=au, title=(m.get("title") or [""])[0], year=year, doi=doi)
    ct = (m.get("container-title") or [""])
    if ct and ct[0]:
        f["journal" if typ == "article" else "booktitle"] = ct[0]
    for k_src, k_bib in (("volume", "volume"), ("issue", "number"), ("page", "pages"), ("article-number", "eid"), ("publisher", "publisher")):
        if m.get(k_src) and (k_bib != "publisher" or typ in ("book", "incollection", "misc")):
            f[k_bib] = m[k_src]
    body = ",\n".join(f"  {k} = {{{str(v).replace('{', '').replace('}', '')}}}" for k, v in f.items() if v)
    return f"@{typ}{{{key},\n{body}\n}}\n"


out, bib = [], []
for r in rows:
    doi = r["doi"].strip()
    rec = dict(r)
    if not doi:
        rec.update(crossref_status="NO DOI (book / conference / software); metadata from the citing document, NOT Crossref-verified")
        bib.append(f"@misc{{{r['key']},\n  note = {{{r['manual_citation']} [NOT DOI-verified]}}\n}}\n")
        out.append(rec)
        continue
    m = fetch(doi)
    if m in (None, "ERROR"):
        rec.update(crossref_status="DOI NOT FOUND in Crossref" if m is None else "network error")
        bib.append(f"@misc{{{r['key']},\n  note = {{{r['manual_citation']} [DOI {doi} could not be verified]}},\n  doi = {{{doi}}}\n}}\n")
    else:
        year = (m.get("issued", {}).get("date-parts") or [[None]])[0][0]
        first = (m.get("author") or [{}])[0].get("family", "")
        title = (m.get("title") or [""])[0]
        ok_year = str(year) in r["manual_citation"]
        ok_auth = first.lower()[:4] in r["manual_citation"].lower() if first else False
        rec.update(crossref_status="VERIFIED" if (ok_year and ok_auth) else "VERIFIED DOI but CHECK: year/first author differ from citing text",
                   crossref_first_author=first, crossref_year=year, crossref_title=title,
                   crossref_journal=(m.get("container-title") or [""])[0], crossref_volume=m.get("volume", ""), crossref_pages=m.get("page", m.get("article-number", "")))
        bib.append(bibtex(r["key"], m, doi))
    out.append(rec)
    time.sleep(0.2)
keys = list(out[0].keys())
for o in out:
    for k in o:
        if k not in keys:
            keys.append(k)
with open(AUD / "reference_verification.csv", "w", newline="", encoding="utf-8") as fh:
    w = csv.DictWriter(fh, fieldnames=keys)
    w.writeheader()
    w.writerows(out)
(AUD / "references.bib").write_text("% Generated by scripts/verify_references.py from Crossref (see reference_verification.csv for status).\n"
                                    "% Entries flagged NOT DOI-verified or CHECK must be confirmed by the team before citation.\n\n" + "\n".join(bib),
                                    encoding="utf-8")
from collections import Counter  # noqa: E402
print(Counter(o["crossref_status"].split(":")[0].split(" (")[0] for o in out))
for o in out:
    if not o["crossref_status"].startswith("VERIFIED") or "CHECK" in o["crossref_status"]:
        print(o["key"], "|", o["crossref_status"], "|", o.get("crossref_first_author"), o.get("crossref_year"), "|", o["manual_citation"][:80])
